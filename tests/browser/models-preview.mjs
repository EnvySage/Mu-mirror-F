import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import fs from 'node:fs/promises'
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const base = process.env.MODELS_PREVIEW_URL || 'http://127.0.0.1:5192'
const screenshots = process.env.MODELS_SCREENSHOT_DIR
try {
  const errors = []
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, reducedMotion: 'reduce' })
  page.on('pageerror', err => errors.push(err.message))
  await page.goto(base + '/models')
  await page.getByRole('button', { name: '新建配置', exact: false }).click()
  await page.getByLabel('配置名称', { exact: true }).fill('日常 DeepSeek')
  await page.getByLabel('模型 ID', { exact: true }).fill('account-owned-model')
  await page.getByLabel('API Key', { exact: false }).fill('preview-secret-never-store')
  await page.getByRole('button', { name: '测试当前填写', exact: true }).click()
  await page.getByText('当前填写 · 模拟结果', { exact: true }).waitFor()
  assert.equal(await page.locator('.profile-row').count(), 0, 'draft test does not save')
  await page.getByLabel('模型 ID', { exact: true }).fill('new-model')
  assert.equal(await page.locator('.connection-result').count(), 0, 'changing draft invalidates old draft result')
  await page.getByRole('button', { name: '保存配置', exact: true }).click()
  await page.locator('.profile-row').first().waitFor()
  assert.equal(await page.getByLabel('API Key', { exact: false }).inputValue(), '')
  assert.equal(await page.locator('.applied-model strong').innerText(), '预览模式', 'save does not apply')
  await page.getByRole('button', { name: '应用此配置', exact: true }).click()
  await page.getByRole('button', { name: '当前已应用', exact: true }).waitFor()
  assert.equal(await page.locator('.applied-model strong').innerText(), 'new-model')
  await page.getByLabel('模型 ID', { exact: true }).fill('updated-model')
  assert.equal(await page.getByRole('button', { name: '当前已应用', exact: true }).isDisabled(), true)
  await page.getByRole('button', { name: '保存配置', exact: true }).click()
  await page.getByText('修改待应用', { exact: true }).waitFor()
  assert.equal(await page.locator('.applied-model strong').innerText(), 'new-model', 'editing active profile retains effective config until apply')
  await page.getByRole('button', { name: '测试已保存配置', exact: true }).click()
  await page.getByText('已保存配置 · 模拟结果', { exact: true }).waitFor()
  await page.getByRole('button', { name: '应用此配置', exact: true }).click()
  await page.getByRole('button', { name: '当前已应用', exact: true }).waitFor()
  assert.equal(await page.locator('.applied-model strong').innerText(), 'updated-model')
  assert.equal(await page.evaluate(() => JSON.stringify(localStorage).includes('preview-secret-never-store')), false)
  if (screenshots) { await fs.mkdir(screenshots, {recursive:true}); await page.screenshot({path: screenshots + '/models-desktop.png'}) }
  await page.getByRole('button', { name: '新建配置', exact: false }).click()
  await page.getByLabel('配置名称', { exact: true }).fill('Anthropic backup')
  await page.getByLabel('服务商', { exact: true }).selectOption('anthropic')
  assert.equal(await page.locator('.advanced-model summary').innerText(), '高级设置 Anthropic')
  await page.getByLabel('模型 ID', { exact: true }).fill('my-claude-model')
  await page.getByLabel('API Key', { exact: false }).fill('other-preview-secret')
  await page.getByRole('button', { name: '保存配置', exact: true }).click()
  await page.locator('.profile-row').filter({hasText:'Anthropic backup'}).waitFor()
  await page.getByRole('button', { name: '应用此配置', exact: true }).click()
  await page.getByRole('button', { name: '当前已应用', exact: true }).waitFor()
  await page.locator('.profile-row').filter({hasText:'日常 DeepSeek'}).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '删除这份配置', exact: true }).click()
  await page.locator('.model-idle').waitFor()
  assert.equal(await page.locator('.profile-row').count(), 1)
  await page.getByRole('button', { name: '记忆检索', exact: true }).click()
  await page.getByRole('button', { name: '测试已保存配置', exact: true }).click()
  await page.getByText('演示环境仅模拟测试，未连接真实检索服务。', {exact:true}).waitFor()
  await page.goto(base + '/settings')
  await page.getByRole('button', { name: '进入模型中心', exact: true }).waitFor()
  assert.equal(await page.locator('#settings-embedding').count(), 0)
  assert.equal(await page.locator('#settings-model .protocol-chips').count(), 0)

  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
  mobile.on('pageerror', err => errors.push(err.message))
  await mobile.goto(base + '/')
  await mobile.waitForURL('**/records')
  await mobile.goto(base + '/models')
  await mobile.getByRole('button', { name: '新建配置', exact: false }).click()
  assert.equal(await mobile.locator('.model-list').isVisible(), false)
  assert.equal(await mobile.locator('.model-heading').isVisible(), false)
  assert.equal(await mobile.locator('.models-page .masthead').isVisible(), false)
  assert.equal(await mobile.locator('.advanced-model').getAttribute('open'), null)
  assert.equal(await mobile.getByLabel('配置名称', { exact:true }).evaluate(el => getComputedStyle(el).fontSize), '16px')
  await mobile.getByLabel('配置名称', { exact: true }).fill('手机配置')
  await mobile.getByLabel('模型 ID', { exact: true }).fill('mobile-model')
  await mobile.getByLabel('API Key', { exact: false }).fill('mobile-preview-secret')
  await mobile.getByRole('button', { name: '保存配置', exact: true }).click()
  await mobile.getByRole('button', { name: '应用此配置', exact: true }).waitFor()
  await mobile.locator('.models-page .page-content').evaluate(el => el.scrollTop = 0)
  if (screenshots) await mobile.screenshot({path: screenshots + '/models-mobile-detail.png'})
  await mobile.getByRole('button', { name: '返回列表', exact: false }).click()
  assert.equal(await mobile.locator('.model-list').isVisible(), true)
  assert.equal(await mobile.locator('.model-detail').count(), 0)
  assert.equal(await mobile.locator('body').evaluate(el => el.scrollWidth > window.innerWidth), false)
  if (screenshots) await mobile.screenshot({path: screenshots + '/models-mobile-list.png'})
  await mobile.goto(base + '/settings')
  await mobile.getByLabel('默认首页').selectOption('chat')
  await mobile.goto(base + '/')
  await mobile.waitForURL('**/chat')
  assert.deepEqual(errors, [])
  console.log('PASS model center preview desktop/mobile: draft test isolated, result invalidated, save/apply split, key blank retained and not stored, active edits pending, saved test, profiles delete/switch, embedding test, compact settings, auto records/explicit chat, mobile list/detail and 16px inputs')
} finally { await browser.close() }
